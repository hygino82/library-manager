    private void loadUserlist(String name) {
        try {
            userlist = userService.getUsers(name);
            if (!userlist.isEmpty()) {
                pupulateTable();
            }
        } catch (DatabaseException e) {
            JOptionPane.showMessageDialog(null, e.getMessage());
        }
    }

    private void pupulateTable() {
        DefaultTableModel model = (DefaultTableModel) tbUsuarios.getModel();

        // limpa a tabela
        model.setRowCount(0);

        for (ResponseUserMinDto b : userlist) {
            model.addRow(new Object[]{
                b.id(),
                b.name(),
                b.attribute(),
                b.acitiveLoan(),
                b.contact()
            });
        }
    }
