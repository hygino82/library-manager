    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        final var nome = txtNome.getText();
        final var contato = txtContato.getText();
        final var atributo = cbAtributo.getSelectedItem().toString();

        final InsertUserDto dto = new InsertUserDto(nome, contato, atributo);
        try {
            if (userService.insertUser(dto)) {
                JOptionPane.showMessageDialog(null, "Usuário " + nome + " salvo com sucesso!");
            } else {
                JOptionPane.showMessageDialog(null, "Erro ao adicionar o usuário!");
            }
        } catch (RuntimeException e) {
            JOptionPane.showMessageDialog(null, e.getMessage());
        }
    }//GEN-LAST:event_btnSalvarActionPerformed

